"""Write the acceptance record for the v0.5 rule files and row corrections (decision D-027).

Lists each rule file written in the sessions of 2026-10-05 and 2026-10-06 with its content hash, and the row
corrections authored under the v0.5 decisions. It does not create the live admission manifest: that file changes how
all 139 rule files of every fund are loaded and belongs to the promotion tool (pipeline/rule_promotion.py).

    python scripts/v05_evidence/rule_acceptance.py > docs/investigations/v05_rule_acceptance.md
"""
import csv
import hashlib
import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
BASE = REPO / "data/overrides/agent_investigate_rules"
FILES = [
    "1287750/exclude_issuer_only_supplemental_rows.json",
    "1287750/recover_2025q1_values_tagged_on_issuer_axis.json",
    "1287750/recover_2025q2_values_tagged_on_issuer_axis.json",
    "1803498/exclude_cash_from_investment_conservation.json",
    "1803498/exclude_footnote_figures_tagged_on_issuer.json",
    "1812554/exclude_affiliate_rollforward_issuer_only_rows.json",
    "1812554/exclude_bocso_issuer_only_rows.json",
    "1837532/exclude_2023q3_genesys_repeated_facts.json",
    "1837532/exclude_industry_instrument_subtotal_rows.json",
]
out = sys.stdout
out.write("# v0.5 rule files and row corrections: acceptance record\n\n")
out.write("Owner ruling 2026-10-06 (in session): accept these as they are, recorded in a manifest of file, evidence and\n"
          "acceptance, without the fleet promotion gate. Generated by `scripts/v05_evidence/rule_acceptance.py`.\n\n"
          "This is a record, not the live `admission_manifest.json`. A file whose hash no longer matches has changed\n"
          "since acceptance and is not covered.\n\n")
out.write("## Rule files (`data/overrides/agent_investigate_rules/`)\n\n| File | sha256 | Scope | Evidence items | What it does |\n|---|---|---|---|---|\n")
for name in FILES:
    path = BASE / name
    body = json.loads(path.read_text(encoding="utf-8"))
    digest = hashlib.sha256(path.read_bytes()).hexdigest()
    what = " ".join(str(body.get("rationale", "")).split())
    what = what[:157] + "..." if len(what) > 160 else what
    out.write("| `%s` | `%s` | %s | %d | %s |\n" % (name, digest[:16], ", ".join(body.get("scope", {}).get("quarters", [])), len(body.get("evidence", [])), what.replace("|", "/")))
out.write("\n## Row corrections (`data/overrides/row_corrections.csv`, author starting `v05-decision`)\n\n"
          "| Fund | Quarter | Field | Value | Row | Reason |\n|---|---|---|---|---|---|\n")
with open(REPO / "data/overrides/row_corrections.csv", newline="", encoding="utf-8") as fh:
    for row in csv.DictReader(fh):
        if row["author"].startswith("v05-decision"):
            out.write("| %s | %s | %s | %s | %s | %s |\n" % (row["cik"], row["report_date"], row["field"], row["value"],
                                                           row["bdc_investment_identifier"][:60].replace("|", "/"), row["reason"][:110].replace("|", "/")))
digest = hashlib.sha256((REPO / "data/overrides/row_corrections.csv").read_bytes()).hexdigest()
out.write("\nFile sha256 at acceptance: `%s`\n" % digest)
