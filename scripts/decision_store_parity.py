"""Read-only: the old outstanding categories against the new statuses, finding by finding.

    python scripts/decision_store_parity.py

Reads docs/investigations/v05_readings/outstanding_status.csv (the sandbox-era status file: one row
per outstanding finding with its detailed state and old category) and the decision store, computes
each finding's status (pipeline.finding_status) and writes the cross-table and every row that falls
outside the expected mapping to docs/investigations/v05_readings/decision_store_parity.md.

Expected: proposal -> needs_owner_ruling, needs_check_repair, or (evidence incomplete or reason
rejected) needs_agent_review / needs_data_fix; verdict -> needs_data_fix or needs_owner_ruling;
review_supported -> by the agent's conclusion; investigated, narrative, unreviewed ->
needs_agent_review. Nothing may map to closed: every row in the file is outstanding.
"""
from __future__ import annotations

import csv
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from pipeline import decision_store, finding_status as fs  # noqa: E402

READ = ROOT / "docs" / "investigations" / "v05_readings"
EXPECTED = {
    "proposal": {fs.NEEDS_OWNER_RULING, fs.NEEDS_CHECK_REPAIR, fs.NEEDS_AGENT_REVIEW, fs.NEEDS_DATA_FIX},
    "verdict": {fs.NEEDS_DATA_FIX, fs.NEEDS_OWNER_RULING, fs.NEEDS_CHECK_REPAIR},
    "review_supported": {fs.NEEDS_DATA_FIX, fs.NEEDS_CHECK_REPAIR, fs.NEEDS_OWNER_RULING},
    "investigated": {fs.NEEDS_AGENT_REVIEW},
    "narrative": {fs.NEEDS_AGENT_REVIEW},
    "unreviewed": {fs.NEEDS_AGENT_REVIEW},
}


def main() -> int:
    with open(READ / "outstanding_status.csv", newline="", encoding="utf-8-sig") as fh:
        rows = list(csv.DictReader(fh))
    entries = decision_store.load_all()
    facts = decision_store.facts_by_finding(entries, rows)
    table: Counter = Counter()
    outside = []
    for r in rows:
        f = facts[r["review_id"]]
        status = fs.status_of(r["state"], f)
        table[(r["category"], status)] += 1
        if status not in EXPECTED.get(r["category"], set()):
            outside.append((r, status, f))
    cats = [c for c in EXPECTED if any(k[0] == c for k in table)]
    cols = [s for s in fs.STATUSES if any(k[1] == s for k in table)]
    lines = ["# Decision store parity: old categories against new statuses", "",
             "Generated by `python scripts/decision_store_parity.py` from outstanding_status.csv (%d outstanding "
             "findings, sandbox-era ledgers) and data/decisions. Read-only." % len(rows), "",
             "| Old category | " + " | ".join(cols) + " | Total |", "|---" * (len(cols) + 2) + "|"]
    for c in cats:
        lines.append("| %s | %s | %d |" % (c, " | ".join(str(table[(c, s)]) for s in cols),
                                          sum(table[(c, s)] for s in cols)))
    lines.append("| **Total** | %s | %d |" % (" | ".join(str(sum(table[(c, s)] for c in cats)) for s in cols), len(rows)))
    lines += ["", "## Outside the expected mapping (%d)" % len(outside), ""]
    if outside:
        lines += ["| CIK | Quarter | Rule | State | Old category | New status | Conclusion | Supported | Proposal |",
                  "|---|---|---|---|---|---|---|---|---|"]
        for r, status, f in sorted(outside, key=lambda x: (x[0]["category"], x[0]["cik"], x[0]["report_date"]))[:400]:
            lines.append("| %s | %s | %s | %s | %s | %s | %s | %s | %s |" % (
                r["cik"], r["report_date"], r["rule_name"], r["state"], r["category"], status,
                f.conclusion or "-", "yes" if f.conclusion_supported else "no", f.proposal_class or "-"))
    else:
        lines.append("None.")
    (READ / "decision_store_parity.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines[:len(cats) + 7]))
    print("outside the expected mapping: %d" % len(outside))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
