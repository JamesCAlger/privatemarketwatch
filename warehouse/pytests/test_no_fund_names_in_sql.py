"""Slice 5 Task 1, item g: no file under models/, macros/, tests/ or seeds/ names a fund of the five v0.5 funds or
writes one of their CIKs (in code, a comment, a description or a seed row). Fund rules live only in the wrapper copies
(warehouse/wrappers/<cik>.json, D10). Diagnostic scripts under scripts/ are exempt, and so are the folders not listed.

The funds are not written here either: they are read from the wrapper copies (one per fund of the five: its CIK from
the file name, its entity_name, its dispatch.rule_prefix with underscores read as spaces) and from seeds/manager_brand.csv
(the manager brand of each of those CIKs). Each name is matched as whole words in any case; each CIK with or without
its leading zeros, not inside a longer number.

One file is exempt by name: seeds/manager_brand.csv, the fund-to-manager-brand reference of every fund in production's
config (generated by scripts/make_manager_brand_seed.py from pipeline/config.py CIK_TO_MANAGER_BRAND). It is a
dimension the marts join on, not a rule, and it lists every fund, not the five.
"""
import csv
import json
import re
from pathlib import Path

WAREHOUSE = Path(__file__).resolve().parent.parent
CHECKED = ["models", "macros", "tests", "seeds"]
EXEMPT = {"seeds/manager_brand.csv"}


def five_funds():
    """(CIKs without leading zeros, names) of the funds that have a wrapper copy."""
    ciks, names = [], set()
    for path in sorted((WAREHOUSE / "wrappers").glob("[0-9]*.json")):
        wrapper = json.loads(path.read_text(encoding="utf-8"))
        ciks.append(path.stem.lstrip("0"))
        names.add(wrapper["entity_name"])
        prefix = (wrapper.get("dispatch") or {}).get("rule_prefix")
        if prefix:
            names.add(prefix.replace("_", " "))
    with open(WAREHOUSE / "seeds" / "manager_brand.csv", encoding="utf-8", newline="") as fh:
        names |= {row["manager_brand"] for row in csv.DictReader(fh) if row["cik"].lstrip("0") in ciks}
    return ciks, sorted(names)


def matcher(ciks, names):
    """A function giving the names and CIKs written in a text."""
    name_re = re.compile(r"(?<![A-Za-z0-9])(" + "|".join(r"\s+".join(map(re.escape, n.split())) for n in names)
                         + r")(?![A-Za-z0-9])", re.IGNORECASE)
    cik_re = re.compile(r"(?<![0-9])0*(" + "|".join(map(re.escape, ciks)) + r")(?![0-9])")

    def hits_in(text):
        return sorted({m.group(0) for m in name_re.finditer(text)} | {m.group(0) for m in cik_re.finditer(text)})
    return hits_in


def test_the_five_funds_are_read():
    ciks, names = five_funds()
    assert len(ciks) == 5
    # each fund gives an entity name and a brand at least; a name may be shared
    assert len(names) >= 5


def test_no_checked_file_names_a_fund_of_the_five():
    hits_in = matcher(*five_funds())
    found = {}
    for folder in CHECKED:
        for path in sorted((WAREHOUSE / folder).rglob("*")):
            rel = path.relative_to(WAREHOUSE).as_posix()
            if not path.is_file() or rel in EXEMPT or "__pycache__" in rel:
                continue
            hits = hits_in(path.read_text(encoding="utf-8", errors="replace"))
            if hits:
                found[rel] = hits
    assert found == {}


def test_the_check_finds_names_and_ciks_and_ignores_longer_words():
    # invented funds
    hits_in = matcher(["1234567", "7654321"], ["Zeta", "Kappa Lambda", "ZKL"])
    assert hits_in("-- it is false on Zeta's four 10-K/As") == ["Zeta"]
    assert hits_in("-- kappa  lambda lines; zkl declares it") == ["kappa  lambda", "zkl"]
    assert hits_in("'0001234567|2026-09-30'") == ["0001234567"]
    assert hits_in("cik 7654321") == ["7654321"]
    # words and numbers that contain a name or a CIK are not it
    assert hits_in("zetas, Antizeta, zklx, Kappa") == []
    assert hits_in("11234567 and 12345678") == []


def test_the_exempt_file_exists():
    for rel in EXEMPT:
        assert (WAREHOUSE / rel).is_file()
