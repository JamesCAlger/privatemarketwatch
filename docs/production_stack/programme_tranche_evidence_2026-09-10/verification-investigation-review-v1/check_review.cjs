const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const {pathToFileURL} = require('node:url');
const {chromium} = require('C:/Users/alger/AppData/Local/npm-cache/_npx/9833c18b2d85bc59/node_modules/playwright');
const root = process.cwd();
const input = path.join(root, 'docs/production_stack/programme_tranche_review.html');
const out = path.join(root, 'scratch/2026-09-10_verification_investigation/browser-review-v1');
fs.mkdirSync(out, {recursive:true});
const assert = (ok, reason) => {if (!ok) throw new Error(reason);};
let browser;
const start = Date.now();
const timer = setTimeout(() => {if(browser) browser.close().finally(()=>process.exit(124)); else process.exit(124);}, 240000);
(async()=>{
  browser = await chromium.launch({headless:true, executablePath:'C:/Users/alger/AppData/Local/ms-playwright/chromium-1223/chrome-win64/chrome.exe'});
  const context = await browser.newContext({viewport:{width:1440,height:1080},acceptDownloads:true});
  const network=[],errors=[];
  context.on('request',request=>{if(/^https?:/.test(request.url()))network.push(request.url());});
  await context.route(/^https?:/,route=>route.abort());
  const page=await context.newPage();
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(pathToFileURL(input).href);
  assert(await page.locator('main section').count()===5,'Expected five review sections');
  assert(await page.locator('textarea').count()===32,'Expected 32 contextual comment boxes');
  assert((await page.locator('#result').innerText()).includes('The three candidate stages completed. Engineering verification is incomplete.'),'Stopped candidate status missing');
  const resultText=await page.locator('#result').innerText();
  assert(resultText.includes('four failure markers'),'Corrected failure count missing');
  assert(resultText.includes('61 targeted tests passed; one known validator test still failed.'),'Investigation outcome missing');
  assert(await page.locator('.metric').count()===50,'Expected all 50 metric results');
  assert(((await page.locator('#criteria').textContent()).match(/UNMEASURED/g)||[]).length===50,'Expected all 50 metrics to remain unmeasured');
  const links=await page.locator('a').evaluateAll(nodes=>nodes.map(node=>node.getAttribute('href')));
  for(const href of links){
    if(href.startsWith('#'))assert(await page.locator(href).count()===1,'Missing section '+href);
    else assert(fs.existsSync(path.resolve(path.dirname(input),decodeURIComponent(href))),'Missing local link '+href);
  }
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Desktop overflow');
  await page.screenshot({path:path.join(out,'desktop.png'),fullPage:false});
  const note='[Keep the unresolved dashes.]\nA second line: \u00a3, <script>literal</script>, [nested] and literal \\n.';
  await page.locator('#note-result').fill(note);
  await page.reload();
  assert(await page.locator('#note-result').inputValue()===note,'Browser draft changed');
  await page.evaluate(()=>{window.showSaveFilePicker=async()=>({name:'review.md',createWritable:async()=>({write:async value=>window.savedReview=value,close:async()=>{window.closedReview=true;}})});});
  await page.locator('#save').focus();await page.keyboard.press('Enter');
  assert(await page.evaluate(()=>window.closedReview),'Save writer did not close');
  assert(await page.evaluate(()=>window.savedReview).then(value=>value.includes(note)),'Save writer changed comment');
  await page.evaluate(()=>{window.showSaveFilePicker=async()=>{throw new DOMException('Cancelled','AbortError');};});
  await page.locator('#save').click();
  assert((await page.locator('#save-status').innerText()).includes('cancelled'),'Cancelled save not surfaced');
  await page.evaluate(()=>{delete window.showSaveFilePicker;});
  const waiting=page.waitForEvent('download');await page.locator('#save').click();const download=await waiting;
  await download.saveAs(path.join(out,'downloaded_review.md'));
  assert(fs.readFileSync(path.join(out,'downloaded_review.md'),'utf8').includes(note),'Downloaded comments changed');
  await page.locator('#expand').click();
  assert(await page.locator('details:not([open])').count()===0,'Details did not expand');
  await page.locator('#expand').click();
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile overflow');
  await page.evaluate(()=>scrollTo(0,0));
  await page.screenshot({path:path.join(out,'mobile.png'),fullPage:false});
  await page.evaluate(()=>{Storage.prototype.setItem=()=>{throw new DOMException('Unavailable','QuotaExceededError');};});
  await page.locator('#note-result').fill('[Keep this draft if storage fails.]');
  assert((await page.locator('#save-status').innerText()).includes('unavailable'),'Storage failure not visible');
  await page.emulateMedia({media:'print'});
  await page.pdf({path:path.join(out,'print-check.pdf'),format:'A4',printBackground:true});
  assert(fs.statSync(path.join(out,'print-check.pdf')).size>10000,'Empty print output');
  assert(errors.length===0,'Browser errors: '+errors.join('; '));
  assert(network.length===0,'Unexpected network requests');
  fs.writeFileSync(path.join(out,'checks.json'),JSON.stringify({status:'pass',input_sha256:crypto.createHash('sha256').update(fs.readFileSync(input)).digest('hex'),sections:5,comment_boxes:32,local_links:links.length,desktop_mobile:true,brackets_unicode_literal_newlines:true,download:true,native_save:'writer and cancellation stubs; OS dialog not automated',storage_failure_visible:true,print:true,network,errors,elapsed_seconds:(Date.now()-start)/1000},null,2));
  console.log('Review page: sources, comments, literal text, download, mobile and print passed.');
})().then(async()=>{clearTimeout(timer);if(browser)await browser.close();}).catch(async error=>{console.error(error);clearTimeout(timer);if(browser)await browser.close();process.exitCode=1;});


